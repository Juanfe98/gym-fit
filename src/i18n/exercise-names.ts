function cleanupSpanishName(value: string) {
  return value
    .replace(/\s+/g, ' ')
    .replace(/\s+([),])/g, '$1')
    .replace(/\(\s+/g, '(')
    .trim()
}

export function getLocalizedExerciseName(name: string, lang: Language): string {
  if (lang === 'en') return name
  return cleanupSpanishName([...phraseReplacements, ...wordReplacements].reduce(
    (text, [pattern, replacement]) => text.replace(pattern, replacement),
    name.toLowerCase()
  ))
}
